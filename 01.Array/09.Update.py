# (Update Operation) ==> Change element at a given index

# Step 1: Original array
array = [1, 2, 3, 4, 5]

# Step 2: Index to update
index = 2   # position where value will change

# Step 3: New value
new_value = 100

# Step 4: Update element
array[index] = new_value

# Step 5: Print updated array
print("After Update:", array)

# Time Complexity: O(1)
# Reason:
# Direct index access → no loop → constant time