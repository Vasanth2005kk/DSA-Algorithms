# (Insert End Operation) ==> Add element at the end

# Step 1: Create an array
array = [1, 2, 3, 4, 5]

# Step 2: Value to insert
value = 100

# Step 3: Insert at end
array.append(value)

# Step 4: Print result
print("Updated Array:", array)

# Time Complexity:
# O(1) → Insert at end (amortized constant time)