# (Sort Operation) ==> Arrange elements in ascending order

# Meaning:
# Sorting rearranges elements from smallest to largest (default)

# Step 1: Create an array
array = [5, 2, 8, 1, 3]

# Step 2: Sort array using built-in method
array.sort()

# Step 3: Print sorted array
print("Sorted Array:", array)

# Time Complexity:
# O(n log n) → Python uses Timsort (efficient sorting algorithm)