# (Sum of Elements) ==> Add all elements (manual)

# Step 1: Original array
array = [1, 2, 3, 4, 5]

# Step 2: Initialize sum
total = 0

# Step 3: Traverse and add
for i in array:
    total += i

# Step 4: Print result
print("Sum of Elements:", total)

# Time Complexity: O(n)
# Reason:
# Loop runs for all elements