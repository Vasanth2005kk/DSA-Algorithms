# (Access Operation) ==> Get element using index

# Step 1: Create an array
array = [1, 2, 3, 4, 5]

# Step 2: Access element using index
# Index starts from 0
result = array[0]

# Step 3: Print the result
print("Element at index 0:", result)

# Time Complexity:
# O(1) → Direct access, no loop needed


# output  --> Element at index 0: 1