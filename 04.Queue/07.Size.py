# (Size Operation) ==> Count elements

# Step 1: Create a queue
queue = [10, 20, 30, 40]

# Step 2: Get the number of elements using len()
size = len(queue)
print("Size of the queue is:", size)

# Time Complexity:
# O(1) → Getting the length of a list is constant time

# output  --> Size of the queue is: 4
