# (Enqueue Operation) ==> Add element at rear

# Step 1: Create a queue
queue = [1, 2, 3, 4]

# Step 2: Define value to enqueue
value = 100

# Step 3: Add element to rear using append
queue.append(value)

# Step 4: Print the queue
print("Queue after enqueue:", queue)

# Time Complexity:
# O(1) → Adding to the end of a list is constant time

# output  --> Queue after enqueue: [1, 2, 3, 4, 100]
