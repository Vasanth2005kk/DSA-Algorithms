# (Display Operation) ==> Print all elements

# Step 1: Create a queue
queue = [1, 2, 3, 4, 5]

# Step 2: Loop through and print elements from front to rear
print("Queue elements (front to rear):")
for element in queue:
    print(element)

# Time Complexity:
# O(n) → Traversing all n elements in the queue

# output  --> Queue elements (front to rear):
# output  --> 1
# output  --> 2
# output  --> 3
# output  --> 4
# output  --> 5
