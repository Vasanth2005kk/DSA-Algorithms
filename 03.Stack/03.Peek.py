# (Peek / Top Operation) ==> View top element

# Step 1: Create a stack
stack = [1, 2, 3, 4]

# Step 2: Access the top element (last element)
# Index -1 refers to the last element in Python list
top_element = stack[-1]

# Step 3: Print the top element
print("Top element is:", top_element)

# Time Complexity:
# O(1) → Direct access using index is constant time

# output  --> Top element is: 4