# (Size Operation) ==> Get number of elements in stack

# Step 1: Create a stack
stack = [1, 2, 3, 4, 5]

# Step 2: Get the size using len()
size = len(stack)

# Step 3: Print the size
print("Stack size is:", size)

# Time Complexity:
# O(1) → len() function is constant time in Python

# output  --> Stack size is: 5