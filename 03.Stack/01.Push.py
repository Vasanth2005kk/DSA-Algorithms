# (Push Operation) ==> Add element to top

# Step 1: Create a stack
stack = [1, 2, 3, 4]

# Step 2: Define value to push
value = 100

# Step 3: Add element to top using append
stack.append(value)

# Step 4: Print the stack
print("Stack after push:", stack)

# Time Complexity:
# O(1) → Adding to the end of a list is constant time

# output  --> Stack after push: [1, 2, 3, 4, 100]
